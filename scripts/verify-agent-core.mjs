import { execFile } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';
const exec = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const core = path.resolve(root, manifest.agentCore.path);
const { stdout } = await exec('git', ['rev-parse', 'HEAD'], { cwd: core });
const actual = stdout.trim();
if (actual !== manifest.agentCore.commit) throw new Error(`Agent Core checkout mismatch: expected ${manifest.agentCore.commit}, received ${actual}.`);
